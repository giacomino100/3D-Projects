"""Landmarks P01..P11 and curvature/band profiles for V1 and V2 -> docs/V2_landmarks.md
and docs/V2/*.png (CLAUDE_REVISION_V2 s.7-8).

    .venv\\Scripts\\python cad\\report_v2.py
"""
import importlib
import json
import os
import sys

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
OUT = os.path.join(ROOT, "docs", "V2")
os.makedirs(OUT, exist_ok=True)


def compute(version):
    import parameters as P1
    if version == "V2":
        import parameters_v2
        sys.modules["parameters"] = parameters_v2
    else:
        sys.modules["parameters"] = P1
    from geometry import planform, surface, landmarks
    for m in (planform, surface, landmarks):
        importlib.reload(m)
    return landmarks.landmarks(), landmarks.profiles(160)


def main():
    lm1, pr1 = compute("V1")
    lm2, pr2 = compute("V2")
    json.dump(dict(V1=dict(landmarks=lm1, profiles=pr1), V2=dict(landmarks=lm2, profiles=pr2)),
              open(os.path.join(OUT, "landmarks_profiles.json"), "w"), indent=1, default=float)

    # --- plots
    fig, ax = plt.subplots(4, 1, figsize=(11, 13), sharex=True)
    for pr, st, lab in ((pr1, "--", "V1"), (pr2, "-", "V2")):
        s = np.array([r["s"] for r in pr])
        ax[0].plot(s, [r["z_mid"] for r in pr], "k" + st, label=f"{lab} Z mid")
        ax[0].plot(s, [r["z_top"] for r in pr], "r" + st, lw=.8, label=f"{lab} Z top edge")
        ax[0].plot(s, [r["z_bot"] for r in pr], "b" + st, lw=.8, label=f"{lab} Z bottom edge")
        dz = np.gradient([r["z_mid"] for r in pr], s)
        ax[1].plot(s, np.degrees(np.arctan(dz)), "k" + st, label=f"{lab} longitudinal slope dZ/ds [deg]")
        ax[1].plot(s, [r["rotation_deg"] for r in pr], "g" + st, label=f"{lab} section rotation [deg]")
        ax[2].plot(s, [np.nan if r["band_top"] is None else r["band_top"] for r in pr], "r" + st, label=f"{lab} top band")
        ax[2].plot(s, [np.nan if r["band_bot"] is None else r["band_bot"] for r in pr], "b" + st, label=f"{lab} bottom band")
        ax[3].plot(s, [r["height"] for r in pr], "k" + st, label=f"{lab} visible height")
    ax[0].set_ylabel("Z [mm] (+ rearward)"); ax[1].set_ylabel("deg"); ax[2].set_ylabel("visible band [mm]")
    ax[3].set_ylabel("height [mm]"); ax[3].set_xlabel("s [mm] from inner tip (X_cad = 472 - s)")
    for a in ax:
        a.grid(alpha=.3); a.legend(fontsize=7, ncol=3)
    ax[0].set_title("81A807925A - curvature validation V1 (dashed) vs V2 (solid)")
    plt.tight_layout(); plt.savefig(os.path.join(OUT, "profiles_V1_vs_V2.png"), dpi=110)

    fig, ax = plt.subplots(figsize=(10, 4))
    names = [l["name"].split()[0] for l in lm2]
    ax.plot(names, [l["Z"] for l in lm1], "o--", label="V1 Z")
    ax.plot(names, [l["Z"] for l in lm2], "s-", label="V2 Z")
    ax.set_ylabel("Z [mm]"); ax.grid(alpha=.3); ax.legend(); ax.set_title("Z at landmarks P01..P11")
    plt.savefig(os.path.join(OUT, "landmarks_Z.png"), dpi=110, bbox_inches="tight")

    # --- smoothness check (first derivative): max jump of dZ/ds between samples
    def maxjump(pr):
        s = np.array([r["s"] for r in pr]); z = np.array([r["z_mid"] for r in pr])
        d = np.gradient(z, s); return float(np.max(np.abs(np.diff(d)))), float(np.max(np.abs(np.gradient(d, s))))
    j1, j2 = maxjump(pr1), maxjump(pr2)

    # --- markdown
    def table(lm):
        rows = ["| Landmark | X_cad | Y | Z | outer-edge tangent (CAD) | face normal (CAD, outward) | visible band [mm] | local edge radius [mm] |",
                "|---|---:|---:|---:|---|---|---:|---:|"]
        for l in lm:
            rows.append(f"| {l['name']} | {l['X']:.1f} | {l['Y']:.1f} | {l['Z']:.1f} | {l['tangent']} | {l['normal']} | "
                        f"{'—' if l['band_width'] is None else l['band_width']} | {l['curvature_radius']} |")
        return "\n".join(rows)
    md = f"""# V2 landmarks — 81A807925A (LEFT)

Generated by `cad/report_v2.py` from the same geometry modules used to build the CAD
(V1 with `parameters.py`, V2 with `parameters_v2.py`). Frame: right-handed CAD,
X toward vehicle right (= inner tip), Y up, Z rearward; `X_cad = 472 − s`.
Landmarks lie on the **outer visible edge** of the front face. "Visible band" =
distance from the outer edge to the opening edge along the inward in-plane normal
(— = the ray reaches no opening: solid plate / terminal). "Local edge radius" =
in-plane radius of curvature of the outer outline at the landmark.

## V2

{table(lm2)}

## V1 (for reference)

{table(lm1)}

## Curvature validation (revision §8)

Plots: `docs/V2/profiles_V1_vs_V2.png` (Z top/mid/bottom, longitudinal slope,
section rotation, top/bottom visible band, visible height along s) and
`docs/V2/landmarks_Z.png`.

| Check | V1 | V2 |
|---|---:|---:|
| max change of dZ/ds between adjacent samples (≈3 mm apart) | {j1[0]:.4f} | {j2[0]:.4f} |
| max d²Z/ds² [1/mm] | {j1[1]:.5f} | {j2[1]:.5f} |
| Z(outer end) − Z(inner tip), mid-height [mm] | {pr1[-1]['z_mid'] - pr1[0]['z_mid']:.1f} | {pr2[-1]['z_mid'] - pr2[0]['z_mid']:.1f} |

Both laws are C¹-smooth (no hinge); V2 starts the rearward wrap at 0.45 L instead
of 0.60 L and has no constant-width rails (see band plot): top band and bottom band
vary along s as traced on the photos.
"""
    open(os.path.join(ROOT, "docs", "V2_landmarks.md"), "w", encoding="utf-8").write(md)
    print("ok", j1, j2)


if __name__ == "__main__":
    main()
