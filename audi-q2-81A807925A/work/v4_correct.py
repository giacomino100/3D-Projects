"""V4 front correction of the OUTER visible edge (opening unchanged).
Rules (see analysis/V3_vs_V4_front_changes.md):
 R1 lower edge s 290-440: regression introduced in V3 by the terminal splice/refit -> displace by the
    alB_1 measured deviation (5 px/mm photo, previously validated by 13 manual stations).
 R2 upper edge s 300-385: both independent front photos agree (alB_1 +0.5..0.6, ccm_1 +0.6..0.96)
    -> displace outward by the SMALLER of the two medians (conservative).
 R3 upper edge s 425-455 (narrow end shoulder): both agree (alB_1 -0.6, ccm_1 -1.25) -> inward by the smaller.
 Everything else: unchanged (single-photo or conflicting evidence)."""
import json, os, re, numpy as np
from scipy.interpolate import splprep, splev, interp1d
from scipy.ndimage import gaussian_filter1d
from reg import Model
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OV = os.path.join(ROOT, "REFERENCE_PACK_V4", "analysis", "overlays")
m = Model("V3")
o = m.PF.spline_points("outer", 1500)
t = np.roll(o, -1, 0) - np.roll(o, 1, 0); n = np.c_[t[:, 1], -t[:, 0]]; n /= np.linalg.norm(n, axis=1)[:, None]   # outward (CCW)
yc = o[:, 1].mean(); upper = o[:, 1] > yc
def med_profile(tag, half):
    d = json.load(open(os.path.join(OV, f"meas_V3_{tag}.json")))["outer"]
    sy = np.array(d["sy"]); dv = np.array(d["dev_mm"], float)
    msk = np.isfinite(dv) & ((sy[:, 1] > yc) if half == "upper" else (sy[:, 1] <= yc))
    s, v = sy[msk, 0], dv[msk]; k = np.argsort(s); s, v = s[k], v[k]
    v = np.convolve(v, np.ones(5) / 5, mode="same")
    return interp1d(s, v, bounds_error=False, fill_value=np.nan)
A_lo = med_profile("front_01", "lower"); A_up = med_profile("front_01", "upper"); B_up = med_profile("front_02", "upper")
disp = np.zeros(len(o)); rule = np.array([""] * len(o), dtype=object)
def taper(s, a, b, w=12.0):
    return np.clip((s - a) / w, 0, 1) * np.clip((b - s) / w, 0, 1)
for k, (s, y) in enumerate(o):
    if not upper[k] and 290 <= s <= 440:
        v = A_lo(s)
        if np.isfinite(v): disp[k] = taper(s, 290, 440) * v; rule[k] = "R1"
    if upper[k] and 300 <= s <= 385:
        a, b = A_up(s), B_up(s)
        if np.isfinite(a) and np.isfinite(b) and np.sign(a) == np.sign(b) and a > 0:
            disp[k] = taper(s, 300, 385) * min(a, b); rule[k] = "R2"
    if upper[k] and 425 <= s <= 455:
        a, b = A_up(s), B_up(s)
        if np.isfinite(a) and np.isfinite(b) and np.sign(a) == np.sign(b) and a < 0:
            disp[k] = taper(s, 425, 455, 8) * max(a, b); rule[k] = "R3"
disp = gaussian_filter1d(disp, 2, mode="wrap")
new = o + disp[:, None] * n
c = np.vstack([new, new[:1]]); tck, _ = splprep([c[:, 0], c[:, 1]], s=0.0005 * len(new), per=True, k=3)
x, y = splev(np.linspace(0, 1, 150, endpoint=False), tck); NEW = np.c_[x, y]
summ = {r: dict(n=int((rule == r).sum()), max_abs_mm=round(float(np.abs(disp[rule == r]).max()), 2) if (rule == r).any() else 0,
                mean_mm=round(float(disp[rule == r].mean()), 2) if (rule == r).any() else 0) for r in ("R1", "R2", "R3")}
json.dump(dict(summary=summ, s=o[:, 0].round(2).tolist(), disp=disp.round(3).tolist(), rule=rule.tolist()),
          open(os.path.join(ROOT, "REFERENCE_PACK_V4", "analysis", "v4_outer_displacement.json"), "w"))
fmt = "[\n" + "".join(f"    ({a:8.2f}, {b:7.2f}),\n" for a, b in NEW) + "]"
src = f'''"""
CAD V4 (front refinement) parameters - 81A807925A / TB2 (LEFT).
Generated by work/v4_correct.py. Imports V3 and overrides ONLY the outer visible edge.
Opening, Z law, sections, clips, rear: = V3 (frozen per CLAUDE_V4_FRONT_REFINEMENT.md).
Rules R1-R3 and evidence: REFERENCE_PACK_V4/analysis/V3_vs_V4_front_changes.md
"""
from parameters_v3 import *          # noqa: F401,F403

VERSION = "V4"
STAGE = "V4 front refinement (outer edge R1-R3)"
OUTER_CPS = {fmt}
'''
open(os.path.join(ROOT, "cad", "parameters_v4.py"), "w", encoding="utf-8").write(src)
print(summ)
