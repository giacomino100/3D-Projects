"""V3-A: XY silhouette correction from measured edge deviations (isolated exact-part photos).

Loop:  register cameras (current model) -> measure normal deviations -> displace the
outline samples by the robust per-sample deviation -> refit INDEPENDENT smoothing
splines (outer, opening) -> write parameters_v3.py -> repeat.
Correction photos : 925_alB_1 (outer + opening; frontal, Leo-b sample),
                    925_alA_1 (outer only; spawplast/pru6165 sample).
Holdout photos    : 925_krik_0 (KRIK sample), corner_4 (installed, assembly) -> validation only.
Z law, clips, thicknesses, rear details: FROZEN (= V2).
"""
import json, os, sys, numpy as np, warnings
warnings.filterwarnings("ignore")
from scipy.interpolate import splprep, splev
from scipy.ndimage import median_filter
from reg import *

CORR = {"925_alB_1": dict(outer=1.0, opening=1.0)}          # frontal: silhouette = face edge
HOLD = ["925_alB_2", "925_alA_1", "925_krik_0"]                 # validation only (lip-aware)
LIP = 2.5 + 4.0                                                  # T_SKIN + D_RET_OUTER (V2, frozen)
PICKS = json.load(open(os.path.join(os.path.dirname(__file__), "picks.json")))
HERE = os.path.dirname(os.path.abspath(__file__))


def register(model, name, cam_prev=None):
    pk = PICKS[name]; ei = EdgeImage(os.path.join(REF, name + ".jpg"))
    if cam_prev is None:
        cam0, _ = (init_camera(model, pk["pts"], ei.W, ei.H) if len(pk["pts"]) >= 4
                   else init_camera_generic(model, pk["pts"], pk.get("curves", []), ei.W, ei.H))
        cam0, _ = fit_from_picks(model, pk["pts"], pk.get("curves", []), ei.W, ei.H, cam0)
    else:
        cam0 = cam_prev
    cam = refine_camera(model, ei, cam0, pk["pts"], iters=2, f_prior=cam0[6], curves=pk.get("curves", []),
                        use_opening=pk.get("use_opening", True))
    lip = None if name in CORR else LIP
    return ei, cam, measure(model, ei, cam, lip=lip)


def smooth_closed(pts, n_out, s_factor):
    c = np.vstack([pts, pts[:1]])
    tck, _ = splprep([c[:, 0], c[:, 1]], s=s_factor * len(pts), per=True, k=3)
    x, y = splev(np.linspace(0, 1, n_out, endpoint=False), tck)
    return np.c_[x, y]


def write_params(outer_cps, opening_cps, tag):
    fmt = lambda a: "[\n" + "".join(f"    ({x:8.2f}, {y:7.2f}),\n" for x, y in a) + "]"
    src = f'''"""
CAD V3 parameters - 81A807925A / TB2 (LEFT). Stage: {tag}
Generated by work/v3a.py (photo registration loop). Imports V2 and overrides ONLY
the XY planform (V3-A). Z law, clips, thicknesses, rear details frozen = V2.
"""
from parameters_v2 import *          # noqa: F401,F403

VERSION = "V3"
STAGE = "{tag}"
SPLINE_SEG_PTS = 60                   # finer spline segments (keep local features, e.g. band step)

# PHOTO_DERIVED (V3-A): outer outline, dense control points, measured on 925_alB_1 + 925_alA_1
OUTER_CPS = {fmt(outer_cps)}

# PHOTO_DERIVED (V3-A): opening outline, INDEPENDENT spline, measured on 925_alB_1 (frontal)
OPENING_CPS = {fmt(opening_cps)}

H = {-np.array(outer_cps)[:, 1].min():.2f}
FILLET_TIMEOUT_S = 5
NUMPY_OFFSET = True                   # offsets computed on the dense polyline (OCC offset2D fails on dense splines)
'''
    open(os.path.join(ROOT, "cad", "parameters_v3.py"), "w", encoding="utf-8").write(src)


def iterate(it, version, cams):
    model = Model(version)
    meas, newcams, rep = {}, {}, {}
    for name in list(CORR) + HOLD:
        ei, cam, m = register(model, name, cams.get(name))
        meas[name] = m; newcams[name] = cam; rep[name] = summary(m)
        print(f"  it{it} {version} {name}: outer MAE {rep[name]['outer']['mae']} mm (n={rep[name]['outer']['n']}), "
              f"opening MAE {rep[name]['opening']['mae']} mm (n={rep[name]['opening']['n']})", flush=True)
    new = {}
    for which, base in (("outer", model.o2[::3]), ("opening", model.i2[::3])):
        n2 = model.normals2d(model.o2 if which == "outer" else model.i2)[::3]
        acc = np.zeros(len(base)); wsum = np.zeros(len(base))
        for name, w in CORR.items():
            if w[which] <= 0:
                continue
            d = np.array(meas[name][which]["dev_mm"], float)
            ok = np.isfinite(d) & (np.abs(d) < 4.0)
            acc[ok] += w[which] * d[ok]; wsum[ok] += w[which]
        dev = np.where(wsum > 0, acc / np.maximum(wsum, 1e-9), np.nan)
        # fill gaps by circular interpolation, then a 5-sample median (keeps steps, kills spikes)
        idx = np.arange(len(dev)); ok = np.isfinite(dev)
        dev = np.interp(idx, idx[ok], dev[ok], period=len(dev))
        dev = median_filter(dev, size=7, mode="wrap")
        from scipy.ndimage import gaussian_filter1d
        dev = gaussian_filter1d(dev, 1.5, mode="wrap")
        pts = base + dev[:, None] * n2
        new[which] = smooth_closed(pts, 90 if which == "outer" else 80, 0.6)
    # keep scale: X extent = L (the scale reference), translate so tip s=0, top y max = 0
    o = new["outer"]; k = model.L / (o[:, 0].max() - o[:, 0].min()); s0 = o[:, 0].min(); y0 = o[:, 1].max()
    T = lambda a: np.c_[(a[:, 0] - s0) * k, (a[:, 1] - y0) * k]
    return T(new["outer"]), T(new["opening"]), newcams, rep, k


def main(n_it=3):
    log = []
    cams = {}
    version = "V2"
    for it in range(n_it):
        oc, ic, cams, rep, k = iterate(it, version, cams)
        log.append(dict(iteration=it, model=version, metrics=rep, rescale=k))
        write_params(oc, ic, f"V3-A iteration {it + 1}")
        version = "V3"
    # final measurement of the last written V3-A
    model = Model("V3"); final = {}
    for name in list(CORR) + HOLD:
        ei, cam, m = register(model, name, cams.get(name))
        final[name] = summary(m); cams[name] = cam
        np.save(os.path.join(HERE, "reg_out", f"cam_V3A_{name}.npy"), cam)
        print(f"  final V3-A {name}: outer MAE {final[name]['outer']['mae']} opening MAE {final[name]['opening']['mae']}")
    log.append(dict(iteration="final", model="V3-A", metrics=final))
    json.dump(log, open(os.path.join(HERE, "reg_out", "v3a_log.json"), "w"), indent=1, default=float)


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 3)
