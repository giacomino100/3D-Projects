"""Generate cad/parameters_v2.py from the multi-view fit (work/fit_v2b.json)."""
import json, os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
r = json.load(open(os.path.join(HERE, "fit_v2b.json")))
import sys; sys.path.insert(0, HERE)
from fit_v2 import spline_curve

L = 472.0
o = np.array(r["outer_cps"]); op = np.array(r["opening_cps"])
oc = spline_curve(o, 4000)
k = L / (oc[:, 0].max() - oc[:, 0].min())
s0, y0 = oc[:, 0].min(), oc[:, 1].max()
T = lambda a: np.c_[(a[:, 0] - s0) * k, (a[:, 1] - y0) * k]
o2, op2 = T(o), T(op)
# Post-fit smoothing (documented in docs/V1_vs_V2.md): opening BOTTOM control points
# between s=250 and s=420 show a ~3 mm wave caused by the grille "plug" contaminating
# the hole mask -> one pass of 3-point moving average on y for those points only.
sm = op2.copy()
for i in range(len(op2)):
    if op2[i, 1] < -25 and 250 < op2[i, 0] < 420:
        sm[i, 1] = (op2[i - 1, 1] + op2[i, 1] + op2[(i + 1) % len(op2), 1]) / 3.0
SMOOTHED = [(round(float(a), 2), round(float(b), 2), round(float(c), 2)) for (a, b), c in zip(op2, sm[:, 1]) if abs(b - c) > 1e-6]
op2 = sm
oc2 = T(oc)
H = float(-oc2[:, 1].min())
scan = [d for d in r["scan"] if "sag" not in d]
best = min(scan, key=lambda d: d["cost"])
scan2 = [d for d in r["scan"] if "sag" in d]
best2 = min(scan2, key=lambda d: d["cost"])
costs = sorted(d["cost"] for d in scan)
info = dict(smoothed_opening_points=SMOOTHED, scale_k=k, H=H, best=best, best2=best2, cost_range=(costs[0], costs[-1]),
            stageA=r["stageA_cost"], v1=r["v1_per"])
json.dump(info, open(os.path.join(HERE, "params_v2_info.json"), "w"), indent=1, default=float)

