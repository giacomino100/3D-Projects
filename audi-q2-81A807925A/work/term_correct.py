"""Terminal refinement - only the corrections supported by >= 2 exact-target specimens:

 R-feature (recess = the two band steps of the opening near END B):
   existence and SHAPE (sharp transition, ~8 mm) confirmed on alB_1 (Leo-b) and ccm_1 (RRR ccm44);
   POSITION and depth taken from alB_1 (2560 px, both tips in frame, camera constrained at both ends),
   because ccm_1 crops END B (its s-scale near the right image border is not constrained).
   -> the CAD opening edges are replaced, for s in the recess windows, by the alB_1 edge points
      (objective background-edge extraction, recess_steps_V5.json), median-filtered, blended over 3 mm.
Everything else in both terminals: unchanged (no 2-specimen agreement; see terminal_overlay_analysis.md)."""
import json, os, numpy as np
from scipy.interpolate import splprep, splev
from scipy.ndimage import median_filter
from reg import Model, ROOT
m = Model("V5")
pts = np.array(json.load(open(os.path.join(ROOT, "TERMINAL_REFINEMENT", "recess_steps_V5.json")))["front_A"])
i = m.PF.spline_points("opening", 4000); yc = i[:, 1].mean()
WIN = {"top": (370.0, 414.0), "bottom": (360.0, 414.0)}
new = i.copy(); log = {}
for half, (a, b) in WIN.items():
    sel = pts[:, 1] > yc if half == "top" else pts[:, 1] <= yc
    p = pts[sel & (pts[:, 0] > a - 6) & (pts[:, 0] < b + 6)]; p = p[np.argsort(p[:, 0])]
    p[:, 1] = median_filter(p[:, 1], size=5, mode="nearest")
    k = np.where(((i[:, 1] > yc) if half == "top" else (i[:, 1] <= yc)) & (i[:, 0] >= a) & (i[:, 0] <= b))[0]
    target = np.interp(i[k, 0], p[:, 0], p[:, 1])
    w = np.clip((i[k, 0] - a) / 3.0, 0, 1) * np.clip((b - i[k, 0]) / 3.0, 0, 1)
    d = w * (target - i[k, 1]); new[k, 1] = i[k, 1] + d
    log[half] = dict(window_s=[a, b], max_abs_change_mm=round(float(np.abs(d).max()), 2), mean_change_mm=round(float(d.mean()), 2))
c = np.vstack([new[::10], new[:1]]); tck, _ = splprep([c[:, 0], c[:, 1]], s=0.0003 * len(c), per=True, k=3)
x, y = splev(np.linspace(0, 1, 160, endpoint=False), tck)
fmt = "[\n" + "".join(f"    ({a:8.2f}, {b:7.2f}),\n" for a, b in zip(x, y)) + "]"
src = f'''"""
Terminal refinement parameters - 81A807925A / TB2 (LEFT). Imports V5 and overrides ONLY the opening
outline inside the END B recess windows (R-feature). Generated by work/term_correct.py.
Evidence and rejected candidates: TERMINAL_REFINEMENT/terminal_changes.md
"""
from parameters_v5 import *          # noqa: F401,F403

VERSION = "V6"
STAGE = "terminal refinement (END B recess steps from alB_1, shape confirmed on ccm_1)"
OPENING_CPS = {fmt}
'''
open(os.path.join(ROOT, "cad", "parameters_v6.py"), "w", encoding="utf-8").write(src)
json.dump(log, open(os.path.join(ROOT, "TERMINAL_REFINEMENT", "recess_correction.json"), "w"), indent=1)
print(log)
