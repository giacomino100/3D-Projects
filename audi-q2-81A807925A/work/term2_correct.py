"""Terminal refinement 2 (V7) - bead + recessed floor model, regular END B loop.

User feedback on V6 (photo alB_1): END A has a RECESS ('rientro') between the two rails, which run straight to
the tip; the END B loop is a REGULAR band, while V6 showed notches / waves there.
Measured on alB_1 (work/term2_measure.py -> TERMINAL_REFINEMENT/bead_measure.json):
  * both rails are raised beads of ~constant width from the outer edge: crease at d = 6.4-7.0 mm (top rail),
    END B loop band (bead only) 6.9-7.5 mm  ->  W_BEAD = 7.2
  * along the opening the face beyond the bead is a lower ledge (top 1.2-1.8 mm, bottom ~4 mm) that ends with
    the two steps near END B (s ~ 380-389, alB_1 + ccm_1); at END A the same lower level is the whole plate.
This script writes cad/parameters_v7.py:
  OPENING_CPS = V6 opening; from s = 362 to the END B tip it is moved, along its normal, onto the inner loop
                contour extracted on alB_1 (work/term2_loop.py: ray casting, back-projected), smoothed
                -> removes the V6 waves / hook of the loop; the two steps (already from alB_1) are kept.
The recess levels (ledge D_LEDGE, END A pocket D_RECESS) are built in geometry/planform.py + surface.py."""
import json, os, numpy as np
from scipy.ndimage import median_filter
from shapely.geometry import Polygon, Point
from reg import Model, ROOT

S_LOOP = 370.0        # from here to the END B tip the opening follows the alB_1 loop contour
m = Model("V6")       # V6 opening = V5 + alB_1 step points (the steps coincide with the loop contour)
i = m.PF.spline_points("opening", 3000)
sy = np.array(json.load(open(os.path.join(ROOT, "TERMINAL_REFINEMENT", "loop_contour_alB1.json"))))
inner = Polygon(i).buffer(-1.5)
sy = sy[[not inner.contains(Point(p)) for p in sy]]          # drop texture hits inside the opening
t = np.roll(i, -1, 0) - np.roll(i, 1, 0); t /= np.linalg.norm(t, axis=1)[:, None]
n = np.c_[t[:, 1], -t[:, 0]]                                  # outward for the CCW outline
off = np.zeros(len(i))
for k in np.where(i[:, 0] >= S_LOOP - 8)[0]:
    r = sy - i[k]; a, b = r @ t[k], r @ n[k]
    sel = (np.abs(a) < 1.2) & (np.abs(b) < 3.0)
    if sel.sum() >= 3:
        off[k] = np.median(b[sel])
off = median_filter(off, size=9, mode="wrap")
off = np.convolve(np.r_[off[-6:], off, off[:6]], np.ones(7) / 7, mode="same")[6:-6]
w = np.clip((i[:, 0] - (S_LOOP - 8)) / 8.0, 0, 1)
new = i + (w * off)[:, None] * n
LOG = dict(points=int(len(sy)), max_offset_mm=round(float(np.abs(w * off).max()), 2),
           mean_abs_offset_mm=round(float(np.abs(w * off)[w > 0].mean()), 2))
q = new[::4]
fmt = "[\n" + "".join(f"    ({a:8.2f}, {b:7.2f}),\n" for a, b in q) + "]"
src = f'''"""
Terminal refinement 2 parameters - 81A807925A / TB2 (LEFT). Imports V6.
Model change: raised rail BEADS of constant width + RECESSED FLOOR between them (END A plate = 'rientro',
ledges along the opening ending with the two steps near END B); END B loop opening on the alB_1 contour.
Generated by work/term2_correct.py. Evidence: TERMINAL_REFINEMENT/terminal_changes.md (V7 section).
"""
from parameters_v6 import *          # noqa: F401,F403

VERSION = "V7"
STAGE = "terminal refinement 2 (bead + recessed floor; regular END B loop)"
W_BEAD = 7.2          # PHOTO_DERIVED alB_1: bead crease at d = 6.4-7.0 (top), loop band 6.9-7.5 mm
D_RECESS = 2.2        # ASSUMED magnitude (existence PHOTO_CONFIRMED: alB_1, alA_3, fre_2): END A pocket set-back, mm
FLOOR_MIN_W = 1.2     # floor strips narrower than this are dropped (no slivers)
OPENING_CPS = {fmt}

# --- recess levels (geometry/planform.py: recess_polygons) ---
D_LEDGE = 1.0         # ASSUMED magnitude: bead -> ledge set-back (ledge along the opening, END B steps)
FLOOR_S_MAX = 392.0   # PHOTO_DERIVED alB_1/ccm_1: ledges end with the steps (s 380-389); END B loop = bead only
POCKET_FIT_S = (135.0, 175.0)   # opening edges fitted here and extended straight to END A
POCKET_S_MAX = 140.0  # pocket runs into the opening start (cut there)
POCKET_RIM = 1.2      # min ledge between bead and pocket around the END A nose
RECESS_SPLINE = False # spline outlines: ledge face self-intersects at the END B ledge end -> polygon (see terminal_changes_V7.md)
'''
open(os.path.join(ROOT, "cad", "parameters_v7.py"), "w", encoding="utf-8").write(src)
json.dump(LOG, open(os.path.join(ROOT, "TERMINAL_REFINEMENT", "loop_correction.json"), "w"), indent=1)
print(LOG, "CPS", len(q))
